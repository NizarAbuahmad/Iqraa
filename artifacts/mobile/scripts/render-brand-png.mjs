/**
 * Renders the Iqrra lockup (`brandLockupSvg` in services/brandLockup.ts) to a
 * PNG and writes it, base64, to services/brandLockupPng.ts — the logo Word
 * exports carry. Rerun after changing constants/brandMark.ts:
 *
 *   node --experimental-strip-types scripts/render-brand-png.mjs
 *
 * Needs Playwright's Chromium (installed in the cloud sessions; locally,
 * `npx playwright install chromium` once).
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const { brandLockupSvg } = await import('../services/brandLockup.ts');

// Three times the size it is shown at, so it prints sharp.
const WIDTH = 390;
const svg = brandLockupSvg(WIDTH);

const browser = await chromium.launch();
const page = await browser.newPage({ deviceScaleFactor: 1 });
await page.setContent(`<!doctype html><html><body style="margin:0;background:transparent">${svg}</body></html>`);
const box = await page.locator('svg').boundingBox();
const png = await page.locator('svg').screenshot({ omitBackground: true });
await browser.close();

const out = fileURLToPath(new URL('../services/brandLockupPng.ts', import.meta.url));
writeFileSync(out, `/**
 * GENERATED by scripts/render-brand-png.mjs from \`brandLockupSvg\` — do not edit.
 * The Iqrra lockup as a transparent PNG, for Word exports (services/brandLockup.ts).
 */
export const BRAND_LOCKUP_PNG_SIZE = { width: ${Math.round(box.width)}, height: ${Math.round(box.height)} } as const;

export const BRAND_LOCKUP_PNG_BASE64 =
  '${png.toString('base64')}';
`);
console.log(`wrote ${out} (${png.length} bytes, ${Math.round(box.width)}x${Math.round(box.height)})`);
