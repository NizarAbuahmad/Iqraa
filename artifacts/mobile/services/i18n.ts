export function getT(lang: Lang): (key: TranslationKey, ...args: any[]) => string {
  const dict = translations[lang] as any;
  return (key: TranslationKey, ...args: any[]) => {
    const val = dict[key];
    if (typeof val === 'function') return val(...args);
    return val ?? key;
  };
}

