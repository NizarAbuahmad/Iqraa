/**
 * «تبسيط الشرح» as plain text — the share sheet, the clipboard, the Word export.
 *
 * No objectives, materials or assessment block, unlike `formatLessonPlanText`:
 * this sheet is handed to a student, and those are the teacher's sections.
 * A check whose `answer` is absent prints its question and nothing under
 * «الإجابات» — nothing established that answer, and a blank beats a guess.
 */
export function formatSimplifiedExplanationText(
  out: SimplifiedExplanationOutput,
  title: string,
  meta: { subject: string; grade: string },
  isAr: boolean,
): string {
  const SEP = '═══════════════════════════════';
  const lines: string[] = [];
  const H = (label: string) => `\n${label}\n${'─'.repeat(label.length)}`;

  lines.push(title);
  lines.push(`${meta.subject} | ${meta.grade}`);
  lines.push(SEP);

  lines.push(H(isAr ? 'الفكرة باختصار' : 'The Big Idea'));
  lines.push(out.bigIdea);

  lines.push(H(isAr ? 'الشرح خطوة بخطوة' : 'Step by Step'));
  out.explanation.forEach((s, i) => lines.push(`${i + 1}. ${s}`));

  if (out.keyWords?.length) {
    lines.push(H(isAr ? 'كلمات مفتاحية' : 'Key Words'));
    out.keyWords.forEach(w => lines.push(`• ${w.term}: ${w.meaning}`));
  }

  lines.push(H(isAr ? 'مثال محلول' : 'Worked Example'));
  lines.push(out.workedExample.text);
  out.workedExample.steps.forEach((s, i) => lines.push(`${i + 1}. ${s}`));
  lines.push(`${isAr ? 'الإجابة:' : 'Answer:'} ${out.workedExample.answer}`);

  lines.push(H(isAr ? 'خطأ شائع' : 'A Common Mistake'));
  lines.push(out.misconception.claim);
  lines.push(out.misconception.correction);

  lines.push(H(isAr ? 'تحقّق من فهمك' : 'Check Your Understanding'));
  out.checks.forEach((c, i) => lines.push(`${i + 1}. ${c.text}`));

  const answered = out.checks
    .map((c, i) => ({ n: i + 1, answer: (c.answer ?? '').trim() }))
    .filter(a => a.answer.length > 0);
  if (answered.length) {
    lines.push(H(isAr ? 'الإجابات' : 'Answers'));
    answered.forEach(a => lines.push(`${a.n}. ${a.answer}`));
  }

  lines.push('\n' + SEP);
  lines.push(isAr ? 'أُنشئ بواسطة اقرأ — مساعد التدريس الذكي' : 'Generated by Iqra — AI Teaching Assistant');

  return lines.join('\n');
}
