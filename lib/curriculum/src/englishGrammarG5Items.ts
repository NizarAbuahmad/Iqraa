/**
 * Grade 5 grammar: the ten authored hub lessons, the «Vocabulary & Grammar» lesson of every unit (spec:
 * docs/superpowers/specs/2026-10-23-english-corner-grammar-g5-design.md). Every item is a whole sentence with its correct
 * answer and a distractor, written by us and checked by a teacher on the printed form; nothing here is pictured.
 *
 * The rule for a distractor: every item is `form` — the distractor is ungrammatical in standard English, never a form
 * that could fit — and comes from one list only: the bare verb for a participle, a past or a third-person form; a
 * doubled or missing auxiliary; the wrong agreement (`has` for `I`, `Have he`); `to` after a modal; a tensed or -ing
 * verb after a modal or `did` (`didn't went`, `should goes`); a misplaced negative (`don't should`); `will` inside a
 * time clause; the wrong relative word (a person word for a thing, `where` for a person); a question in statement word
 * order; `more` on a short adjective or `-er`/`-est` on a long one; a doubled comparative marker (`more worse`,
 * `the most kindest`); a regular ending on an irregular verb. Never `the most` + a short adjective (`the most kind`),
 * never `-fuller`/`-fullest` on a -ful adjective, never `which` for a person, never a past simple (`saw`, `did`) for a
 * participle, never `ever` in a statement. Every sentence is nine words or fewer, so Build always takes it whole. No
 * names: a pronoun or a family word (`Mum`, `Dad`, `Granny`). `statement` is the book's own line for the lesson id
 * (its `objectives[0]`, read back by a test from the data file).
 *
 * Imports only types from the engine: `englishGrammar.ts` imports `englishGrammarG5.ts`, which imports this file.
 */
